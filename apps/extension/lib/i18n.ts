export type Strings = typeof fr;
export const strings: Strings = (globalThis.navigator?.language ?? 'fr').toLowerCase().startsWith('en')
  ? en
  : fr;
export const lang = strings === en ? 'en' : 'fr';

export function stepsCaptured(n: number): string {
  // En français, 0 s'accorde au singulier (« 0 étape capturée ») ; en anglais, au pluriel
  const one = n === 1 || (n === 0 && lang === 'fr');
  return (one ? strings.stepsCaptured_one : strings.stepsCaptured_other).replace('{{count}}', String(n));
}

/** L25-01 : puce de l'onglet suivi dans la barre d'enregistrement, et son annonce. */
export function tabChip(n: number, title: string): { label: string; announce: string } {
  const t = title.slice(0, 40);
  const fill = (x: string) => x.replace('{{n}}', String(n)).replace('{{title}}', t);
  return { label: fill(strings.tabChip), announce: fill(strings.tabAnnounce) };
}

/** L26-04 : prochaine étape à capturer, dans la barre d'enregistrement. */
export function guideChip(g: { title: string; n: number; total: number }): string {
  return strings.guideChip
    .replace('{{title}}', g.title.slice(0, 60))
    .replace('{{n}}', String(g.n))
    .replace('{{total}}', String(g.total));
}

/** L60 §2 : pastille de la barre (« 3 étapes », « 1 page », « 2 clics repérés »). */
export function barCount(kind: 'steps' | 'pages' | 'clicks', n: number): string {
  const key = kind === 'steps' ? 'barSteps' : kind === 'pages' ? 'barPages' : 'barClicksSeen';
  const one = n === 1 || (n === 0 && lang === 'fr');
  return strings[`${key}_${one ? 'one' : 'other'}` as keyof typeof strings].replace('{{n}}', String(n));
}
