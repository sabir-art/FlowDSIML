/** Interpolation {{x}} et pluriel _one / _other (chaînes du quiz, format docs/ux/i18n). */
export function fmt(
  dict: Record<string, string>,
  key: string,
  vars: Record<string, string | number> = {},
): string {
  const plural = typeof vars.count === 'number' ? (vars.count === 1 ? '_one' : '_other') : '';
  const raw = dict[`${key}${plural}`] ?? dict[key] ?? key;
  return raw.replace(/{{(\w+)}}/g, (_, k: string) => String(vars[k] ?? ''));
}
